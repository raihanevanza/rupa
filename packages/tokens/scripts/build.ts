/**
 * Builds every output of @rupa-ui/tokens from src/.
 *
 * Style Dictionary resolves references and validates the source once per brand × mode.
 * The results are then merged: colors become `light-dark()` pairs per brand, so a single
 * CSS variable follows the nearest `color-scheme` (set by `.dark` / `data-theme`) and the
 * nearest `data-brand`, with no selector combinations.
 */
import { mkdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import StyleDictionary from 'style-dictionary'
import { BRANDS, MODES, PREFIX, type Brand, type Mode } from './config.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = join(root, 'src')
const dist = join(root, 'dist')

interface Token {
  path: string[]
  $type?: string
  $value: unknown
  $description?: string
}

interface ShadowLayer {
  alpha: number
  offsetX: string
  offsetY: string
  blur: string
  spread: string
}

type ColorSet = Record<string, string>

async function resolve(brand: Brand, mode: Mode): Promise<Token[]> {
  const sd = new StyleDictionary({
    source: [
      join(src, 'global/font.json'),
      join(src, 'global/layout.json'),
      join(src, 'global/effect.json'),
      join(src, 'primitive/palette.json'),
      join(src, `brands/${brand}/${mode}.json`),
      join(src, `status/${mode}.json`),
    ],
    usesDtcg: true,
    log: { verbosity: 'verbose', warnings: 'error', errors: { brokenReferences: 'throw' } },
    platforms: { js: { transforms: [] } },
  })
  const { allTokens } = await sd.getPlatformTokens('js')
  return allTokens as unknown as Token[]
}

const cssName = (path: string[]) => `--${PREFIX}-${path.join('-')}`
const lower = (hex: string) => hex.toLowerCase()

function cssValue(token: Token): string {
  const v = token.$value
  switch (token.$type) {
    case 'fontFamily':
      return (v as string[]).map((f) => (/\s/.test(f) ? `'${f}'` : f)).join(', ')
    case 'cubicBezier':
      return `cubic-bezier(${(v as number[]).join(', ')})`
    case 'shadow':
      return (v as ShadowLayer[])
        .map(
          (l) =>
            `${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} color-mix(in srgb, var(--${PREFIX}-color-shadow) ${Math.round(l.alpha * 100)}%, transparent)`,
        )
        .join(', ')
    default:
      return String(v)
  }
}

const camel = (s: string) => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())
const remToPx = (v: string) => (v.endsWith('rem') ? parseFloat(v) * 16 : parseFloat(v))

function hexToRgba(hex: string, alpha: number) {
  const n = parseInt(hex.slice(1, 7), 16)
  return `rgba(${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}, ${alpha})`
}

function nest(tokens: Token[], value: (t: Token) => unknown) {
  const out: Record<string, unknown> = {}
  for (const t of tokens) {
    let node = out
    t.path.slice(0, -1).forEach((k) => {
      node = (node[k] ??= {}) as Record<string, unknown>
    })
    node[t.path.at(-1)!] = value(t)
  }
  return out
}

function dts(v: unknown, indent = ''): string {
  if (Array.isArray(v)) return `readonly [${v.map((x) => dts(x)).join(', ')}]`
  if (v && typeof v === 'object') {
    const inner = indent + '  '
    const entries = Object.entries(v).map(([k, x]) => `${inner}readonly '${k}': ${dts(x, inner)}`)
    return `{\n${entries.join('\n')}\n${indent}}`
  }
  return typeof v === 'string' ? `'${v.replace(/'/g, "\\'")}'` : String(v)
}

const header =
  '/* Generated by @rupa-ui/tokens. Do not edit; change packages/tokens/src instead. */\n'

async function write(file: string, content: string) {
  const path = join(dist, file)
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, content)
}

async function main() {
  // Resolve every brand × mode; global tokens must come out identical in all of them.
  const colors = {} as Record<Brand, Record<Mode, ColorSet>>
  const descriptions: Record<string, string> = {}
  let globals: Token[] | undefined

  for (const brand of BRANDS) {
    colors[brand] = {} as Record<Mode, ColorSet>
    for (const mode of MODES) {
      const all = await resolve(brand, mode)
      const semantic = all.filter((t) => t.path[0] === 'color')
      colors[brand][mode] = Object.fromEntries(
        semantic.map((t) => [t.path.slice(1).join('-'), lower(String(t.$value))]),
      )
      for (const t of semantic) {
        if (t.$description) descriptions[t.path.slice(1).join('-')] ??= t.$description
      }
      const g = all.filter((t) => t.path[0] !== 'color' && t.path[0] !== 'palette')
      if (!globals) globals = g
      else if (JSON.stringify(g.map((t) => t.path)) !== JSON.stringify(globals.map((t) => t.path)))
        throw new Error(`Global tokens differ for ${brand}/${mode}`)
    }
  }
  if (!globals) throw new Error('No tokens resolved')

  // Every brand × mode must define the same semantic colors, in the same order.
  const names = Object.keys(colors[BRANDS[0]].light)
  for (const brand of BRANDS)
    for (const mode of MODES) {
      const got = Object.keys(colors[brand][mode])
      const missing = names.filter((n) => !got.includes(n))
      const extra = got.filter((n) => !names.includes(n))
      if (missing.length || extra.length)
        throw new Error(
          `${brand}/${mode}: missing [${missing.join(', ')}] extra [${extra.join(', ')}]`,
        )
    }

  await rm(dist, { recursive: true, force: true })

  // ---------- CSS ----------
  const globalCss = globals.map((t) => `  ${cssName(t.path)}: ${cssValue(t)};`).join('\n')
  const brandCss = BRANDS.map((brand, i) => {
    const selector = i === 0 ? `:root,\n[data-brand='${brand}']` : `[data-brand='${brand}']`
    const lines = names.map(
      (n) =>
        `  --${PREFIX}-color-${n}: light-dark(${colors[brand].light[n]}, ${colors[brand].dark[n]});`,
    )
    return `${selector} {\n${lines.join('\n')}\n}`
  }).join('\n\n')
  const modeCss = [
    `:root,\n.light,\n[data-theme='light'] {\n  color-scheme: light;\n}`,
    `.dark,\n[data-theme='dark'] {\n  color-scheme: dark;\n}`,
    `[data-theme='system'] {\n  color-scheme: light dark;\n}`,
  ].join('\n\n')
  await write(
    'css/tokens.css',
    `${header}\n:root {\n${globalCss}\n}\n\n/* Colors: one rule per brand; light-dark() follows the nearest color-scheme. */\n${brandCss}\n\n/* Modes */\n${modeCss}\n`,
  )

  // ---------- Tailwind v4 ----------
  const tw4 = [
    ...names.map((n) => `  --color-${n}: var(--${PREFIX}-color-${n});`),
    `  --font-sans: var(--${PREFIX}-font-family-sans);`,
    `  --font-mono: var(--${PREFIX}-font-family-mono);`,
    ...globals
      .filter((t) => t.path[0] === 'radius')
      .map((t) => `  --radius-${t.path[1]}: var(${cssName(t.path)});`),
    ...globals
      .filter((t) => t.path[0] === 'shadow')
      .map((t) => `  --shadow-${t.path[1]}: var(${cssName(t.path)});`),
    ...globals
      .filter((t) => t.path[0] === 'motion' && t.path[1] === 'easing')
      .map((t) => `  --ease-${t.path[2]}: var(${cssName(t.path)});`),
  ]
  await write(
    'tailwind/v4.css',
    `${header}/* Use after \`@import 'tailwindcss';\` and \`@import '@rupa-ui/tokens/css';\` */\n@theme inline {\n${tw4.join('\n')}\n}\n\n@custom-variant dark (&:where(.dark, .dark *, [data-theme='dark'], [data-theme='dark'] *));\n`,
  )

  // ---------- Tailwind v3 preset ----------
  const tw3Colors = names
    .map(
      (n) =>
        `    '${n}': 'color-mix(in srgb, var(--${PREFIX}-color-${n}) calc(<alpha-value> * 100%), transparent)',`,
    )
    .join('\n')
  const tw3 = (group: string, key: (t: Token) => string) =>
    globals!
      .filter((t) => t.path[0] === group)
      .map((t) => `    '${key(t)}': 'var(${cssName(t.path)})',`)
      .join('\n')
  await write(
    'tailwind/preset.js',
    `${header}/** Tailwind CSS v3 preset. Also import '@rupa-ui/tokens/css' in your app. */
export default {
  darkMode: ['variant', "&:where(.dark, .dark *, [data-theme='dark'], [data-theme='dark'] *)"],
  theme: {
    extend: {
      colors: {
${tw3Colors.replace(/^ {4}/gm, '        ')}
      },
      fontFamily: {
        sans: 'var(--${PREFIX}-font-family-sans)',
        mono: 'var(--${PREFIX}-font-family-mono)',
      },
      borderRadius: {
${tw3('radius', (t) => t.path[1]!).replace(/^ {4}/gm, '        ')}
      },
      boxShadow: {
${tw3('shadow', (t) => t.path[1]!).replace(/^ {4}/gm, '        ')}
      },
    },
  },
}
`,
  )
  await write(
    'tailwind/preset.d.ts',
    `declare const preset: { darkMode: unknown; theme: { extend: Record<string, unknown> } }\nexport default preset\n`,
  )

  // ---------- JS / TS ----------
  const tokens = nest(globals, (t) => (t.$type === 'shadow' ? cssValue(t) : t.$value))
  const data = { brands: BRANDS, modes: MODES, colors, tokens }
  await write('tokens.json', JSON.stringify(data, null, 2) + '\n')

  const union = (xs: readonly string[]) => xs.map((x) => `'${x}'`).join(' | ')
  await write(
    'index.js',
    `${header}
export const prefix = '${PREFIX}'
export const brands = ${JSON.stringify(BRANDS)}
export const modes = ${JSON.stringify(MODES)}
export const semanticColors = ${JSON.stringify(names)}
/** Resolved hex values: colors[brand][mode][name]. */
export const colors = ${JSON.stringify(colors, null, 2)}
/** What each semantic color is for. */
export const colorDescriptions = ${JSON.stringify(descriptions, null, 2)}
/** Brand-independent tokens (typography, spacing, radius, shadow, motion, z-index). */
export const tokens = ${JSON.stringify(tokens, null, 2)}
/** \`cssVar('color-ink')\` → \`'var(--${PREFIX}-color-ink)'\` */
export const cssVar = (name) => \`var(--${PREFIX}-\${name})\`
`,
  )
  await write(
    'index.d.ts',
    `${header}
export type Brand = ${union(BRANDS)}
export type Mode = ${union(MODES)}
export type SemanticColor = ${union(names)}
export type ColorSet = Record<SemanticColor, string>
export declare const prefix: '${PREFIX}'
export declare const brands: readonly Brand[]
export declare const modes: readonly Mode[]
export declare const semanticColors: readonly SemanticColor[]
export declare const colors: Record<Brand, Record<Mode, ColorSet>>
export declare const colorDescriptions: Partial<Record<SemanticColor, string>>
export declare const tokens: ${dts(tokens)}
export declare function cssVar(name: \`color-\${SemanticColor}\` | (string & {})): string
`,
  )

  // ---------- React Native ----------
  const rnPalette = (set: ColorSet) => {
    const p: Record<string, unknown> = {}
    for (const [k, v] of Object.entries(set)) {
      if (/^series-\d$/.test(k)) continue
      p[camel(k)] = v
    }
    p.series = names.filter((n) => /^series-\d$/.test(n)).map((n) => set[n])
    return p
  }
  const palettes = Object.fromEntries(
    BRANDS.map((b) => [b, Object.fromEntries(MODES.map((m) => [m, rnPalette(colors[b][m])]))]),
  )
  const px = (group: string) =>
    Object.fromEntries(
      globals!
        .filter((t) => t.path[0] === group)
        .map((t) => [camel(t.path.slice(1).join('-')), remToPx(String(t.$value))]),
    )
  const shadows = Object.fromEntries(
    BRANDS.map((b) => [
      b,
      Object.fromEntries(
        MODES.map((m) => [
          m,
          Object.fromEntries(
            globals!
              .filter((t) => t.$type === 'shadow')
              .map((t) => [
                t.path[1],
                (t.$value as ShadowLayer[])
                  .map(
                    (l) =>
                      `${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${hexToRgba(colors[b][m].shadow!, l.alpha)}`,
                  )
                  .join(', '),
              ]),
          ),
        ]),
      ),
    ]),
  )
  const fontSize = Object.fromEntries(
    globals
      .filter((t) => t.path[0] === 'font' && t.path[1] === 'size')
      .map((t) => [t.path[2], remToPx(String(t.$value))]),
  )
  const paletteKeys = Object.keys(rnPalette(colors[BRANDS[0]].light)).filter((k) => k !== 'series')
  const seriesCount = names.filter((n) => /^series-\d$/.test(n)).length
  await write(
    'react-native/index.js',
    `${header}
/** palettes[brand][mode]: same values as the web tokens, keys in camelCase. */
export const palettes = ${JSON.stringify(palettes, null, 2)}
/** Spacing, radius, font size, and control sizes in dp. */
export const space = ${JSON.stringify(px('space'), null, 2)}
export const radius = ${JSON.stringify(px('radius'), null, 2)}
export const fontSize = ${JSON.stringify(fontSize, null, 2)}
export const size = ${JSON.stringify(px('size'), null, 2)}
/** boxShadow strings (React Native 0.76+). */
export const shadows = ${JSON.stringify(shadows, null, 2)}
const FAMILY = {
  regular: 'PlusJakartaSans-Regular',
  medium: 'PlusJakartaSans-Medium',
  semibold: 'PlusJakartaSans-SemiBold',
  bold: 'PlusJakartaSans-Bold',
}
/**
 * Android picks custom fonts by file name, so each weight is its own family.
 * Use \`font('semibold')\` instead of \`fontWeight\` (which can double-bold on Android).
 */
export const font = (weight = 'regular') => ({ fontFamily: FAMILY[weight] })
export const fontFamily = (weight = 'regular') => FAMILY[weight]
`,
  )
  const numRecord = (o: Record<string, number>) =>
    `{ ${Object.keys(o)
      .map((k) => `readonly ${/^\d/.test(k) ? `'${k}'` : k}: number`)
      .join('; ')} }`
  await write(
    'react-native/index.d.ts',
    `${header}
import type { Brand, Mode } from '../index.js'
export type { Brand, Mode }
export interface Palette {
${paletteKeys.map((k) => `  ${k}: string`).join('\n')}
  series: [${Array(seriesCount).fill('string').join(', ')}]
}
export type Weight = 'regular' | 'medium' | 'semibold' | 'bold'
export declare const palettes: Record<Brand, Record<Mode, Palette>>
export declare const space: ${numRecord(px('space'))}
export declare const radius: ${numRecord(px('radius'))}
export declare const fontSize: ${numRecord(fontSize)}
export declare const size: ${numRecord(px('size'))}
export declare const shadows: Record<Brand, Record<Mode, Record<${union(globals.filter((t) => t.$type === 'shadow').map((t) => t.path[1]!))}, string>>>
export declare function font(weight?: Weight): { fontFamily: string }
export declare function fontFamily(weight?: Weight): string
`,
  )

  console.log(
    `@rupa-ui/tokens: ${BRANDS.length} brands × ${MODES.length} modes, ${names.length} semantic colors, ${globals.length} global tokens → dist/`,
  )
}

await main()
