import { chromium } from '@playwright/test'
const D = process.argv[2]
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 1280, height: 860 } })
const p = await ctx.newPage()
p.on('pageerror', (e) => console.log('pageerror', e.message))
await p.goto('http://localhost:5199/', { waitUntil: 'networkidle' })
await p.getByLabel('Email').fill('demo@local.test')
await p.getByLabel('Password', { exact: true }).fill('demo12345')
await p.getByRole('button', { name: 'Masuk' }).click()
await p.waitForTimeout(2000)
await p.screenshot({ path: `${D}/dr-onboard.png`, fullPage: true })
await p.getByLabel('Nama rumah tangga').fill('Keluarga Lestari')
await p.getByLabel('Nama orang 1').fill('Dewi')
const second = p.getByLabel('Nama orang 2')
if (await second.count()) await second.fill('Budi')
await p.locator('button[type=submit]').first().click()
await p.waitForTimeout(3000)
console.log('url', p.url(), 'h1', await p.locator('h1').allTextContents())
await ctx.storageState({ path: `${D}/dr-state.json` })
await p.screenshot({ path: `${D}/dr-after.png`, fullPage: true })
await b.close()
